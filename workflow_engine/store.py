"""Minimal persistence contract shared by workflow execution backends."""

from typing import Any, Dict, Protocol, Sequence


class WorkflowStore(Protocol):
    """Operations used by the sequential engine; SQLiteStore remains compatible."""

    def initialize(self, workflow_id: str, definition: Dict[str, Any], task_ids: Sequence[str]) -> None: ...
    def workflow_lock(self, workflow_id: str): ...
    def recover_running(self, workflow_id: str) -> None: ...
    def task_rows(self, workflow_id: str) -> Dict[str, Dict[str, Any]]: ...
    def set_task(self, workflow_id: str, task_id: str, state: str, error: str = None) -> None: ...
    def set_workflow(self, workflow_id: str, state: str, error: str = None) -> None: ...
